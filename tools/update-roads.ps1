# Rebuilds js/claims.js from GriefPrevention claims shown on the Lotus squaremap.
# Run from anywhere:  powershell -ExecutionPolicy Bypass -File Highway\tools\update-roads.ps1
#
# It saves every claim owned by the players listed in ROAD_SETTINGS.owners (js/data.js).
# Which of those claims count as road (width, length, ignored claims) and the road names are
# decided by the site itself from the settings in data.js, so editing those needs no re-run.
# Re-run this only when claims change in game or you change the owners list.
# (The browser can't read the map's claim data directly: it's 5+ MB and the server doesn't allow
# cross-site requests, so the claims are downloaded here and saved with the site.)

$dataJs = [IO.File]::ReadAllText((Join-Path $PSScriptRoot "..\js\data.js"))
$m = [regex]::Match($dataJs, 'owners\s*:\s*\[([^\]]*)\]')
if (-not $m.Success) { throw "Couldn't find ROAD_SETTINGS.owners in js/data.js" }
$owners = [regex]::Matches($m.Groups[1].Value, '"([^"]+)"|''([^'']+)''') | ForEach-Object { ($_.Groups[1].Value + $_.Groups[2].Value) }
if (-not $owners) { throw "ROAD_SETTINGS.owners in js/data.js is empty" }

$url = "https://lotus.blossomcraft.org/tiles/minecraft_overworld/markers.json"
Write-Host "Downloading claims from $url ..."
$json = (New-Object System.Net.WebClient).DownloadString($url) | ConvertFrom-Json
$claims = ($json | Where-Object { $_.id -eq "griefprevention" }).markers

$lines = foreach ($c in $claims) {
  if ($c.type -ne "rectangle") { continue }
  $owner = $null
  foreach ($o in $owners) { if ($c.popup -match ">$([regex]::Escape($o))<") { $owner = $o } }
  if (-not $owner) { continue }
  $x1 = [Math]::Min($c.points[0].x, $c.points[1].x); $x2 = [Math]::Max($c.points[0].x, $c.points[1].x)
  $z1 = [Math]::Min($c.points[0].z, $c.points[1].z); $z2 = [Math]::Max($c.points[0].z, $c.points[1].z)
  "  { owner: `"$owner`", x1: $x1, z1: $z1, x2: $x2, z2: $z2 }"
}

$out = @"
// GENERATED by tools/update-roads.ps1 on $(Get-Date -Format "yyyy-MM-dd") - don't edit by hand, re-run the script.
// Claims owned by $($owners -join ", "). Road settings, ignored claims and road names are in data.js.
const CLAIMS = [
$($lines -join ",`r`n")
];
"@
$dest = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot "..\js\claims.js"))
[IO.File]::WriteAllText($dest, $out, (New-Object System.Text.UTF8Encoding $false))
"Saved $dest ($(@($lines).Count) claims by $($owners -join ', '))"
